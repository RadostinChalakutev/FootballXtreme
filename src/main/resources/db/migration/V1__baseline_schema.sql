CREATE TABLE pitches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE working_hours (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_of_week VARCHAR(255) NOT NULL UNIQUE,
    opening_time TIME NOT NULL,
    closing_time TIME NOT NULL,
    closed BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pitch_id BIGINT NOT NULL,
    date DATE NOT NULL,
    start_time TIME NOT NULL,
    duration_minutes INTEGER NOT NULL,
    customer_name VARCHAR(255) NOT NULL,
    customer_email VARCHAR(255) NOT NULL,
    customer_phone VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    CONSTRAINT fk_reservations_pitch FOREIGN KEY (pitch_id) REFERENCES pitches (id)
);

CREATE TABLE blocked_times (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pitch_id BIGINT NOT NULL,
    date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    reason VARCHAR(255),
    CONSTRAINT fk_blocked_times_pitch FOREIGN KEY (pitch_id) REFERENCES pitches (id)
);

CREATE INDEX idx_reservations_pitch_date ON reservations (pitch_id, date);
CREATE INDEX idx_blocked_times_pitch_date ON blocked_times (pitch_id, date);
